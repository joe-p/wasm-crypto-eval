use crate::error::{RegisterHostFunctionSnafu, Result};
use alloc::boxed::Box;
use alloc::string::{String, ToString};
use alloc::vec::Vec;
use core::any::Any;
use wasmi::errors::LinkerError;
use wasmi::{Config, Engine, Linker, StoreLimits, StoreLimitsBuilder};

/// Type-erased, per-program payload attached to a [`wasmi::Store`].
///
/// A program's identity (and anything else a host function needs) is installed
/// as the store's user data. Keeping the payload behind a [`Box<dyn Any + Send>`]
/// lets host functions recover it with a checked downcast rather than a pointer
/// cast, so a mismatched type is denied instead of reinterpreted.
pub struct HostState {
    value: Box<dyn Any + Send>,
    limits: StoreLimits,
}

impl HostState {
    pub(crate) fn new(value: Box<dyn Any + Send>, limits: StoreLimits) -> Self {
        HostState { value, limits }
    }

    /// Recovers an owned clone of the installed payload, or `None` if the
    /// requested type does not match.
    pub fn get<T: Any + Clone>(&self) -> Option<T> {
        self.value.as_ref().downcast_ref::<T>().cloned()
    }

    /// Borrows the installed payload, or `None` if the requested type does not
    /// match.
    pub fn value_ref<T: Any>(&self) -> Option<&T> {
        self.value.as_ref().downcast_ref::<T>()
    }

    pub(crate) fn limits_mut(&mut self) -> &mut StoreLimits {
        &mut self.limits
    }
}

/// Engine-wide execution limits.
///
/// These apply to every program instantiated from the [`WasmRuntime`], matching
/// wasmi's engine-level configuration model.
pub struct RuntimeConfig {
    /// Maximum value-stack height, in bytes.
    pub max_stack_height: Option<usize>,
    /// Maximum call recursion depth.
    pub max_recursion_depth: Option<usize>,
    /// Whether execution consumes fuel (needed for [`crate::program::ProgramConfig::fuel`]).
    pub consume_fuel: bool,
}

impl Default for RuntimeConfig {
    fn default() -> Self {
        RuntimeConfig {
            max_stack_height: Some(1 << 16),
            max_recursion_depth: Some(1024),
            consume_fuel: true,
        }
    }
}

/// Deferred registration for a host function, invoked once per [`WasmRuntime`].
type RegisterFn =
    dyn Fn(&mut Linker<HostState>) -> core::result::Result<(), LinkerError> + Send + Sync;

/// A host function that can be registered on a [`WasmRuntime`]'s linker.
///
/// Registration is deferred to a closure so that the concrete
/// [`wasmi::Linker::func_wrap`] call can be generated by
/// `#[wasm_host_function]` without exposing wasmi's generics to callers.
pub struct WasmHostFunction {
    name: String,
    register: Box<RegisterFn>,
}

impl WasmHostFunction {
    pub fn new(
        name: impl Into<String>,
        register: impl Fn(&mut Linker<HostState>) -> core::result::Result<(), LinkerError>
        + Send
        + Sync
        + 'static,
    ) -> Self {
        WasmHostFunction {
            name: name.into(),
            register: Box::new(register),
        }
    }
}

/// The Wasmi interpreter plus the host functions linked into every program.
pub struct WasmRuntime {
    engine: Engine,
    linker: Linker<HostState>,
}

impl WasmRuntime {
    pub fn new(config: &RuntimeConfig, host_functions: Vec<WasmHostFunction>) -> Result<Self> {
        let mut wasmi_config = Config::default();
        if let Some(height) = config.max_stack_height {
            wasmi_config.set_max_stack_height(height);
        }
        if let Some(depth) = config.max_recursion_depth {
            wasmi_config.set_max_recursion_depth(depth);
        }
        wasmi_config.consume_fuel(config.consume_fuel);

        let engine = Engine::new(&wasmi_config);
        let mut linker = Linker::new(&engine);

        for host_fn in &host_functions {
            (host_fn.register)(&mut linker).map_err(|error| {
                RegisterHostFunctionSnafu {
                    name: host_fn.name.clone(),
                    message: error.to_string(),
                }
                .build()
            })?;
        }

        Ok(WasmRuntime { engine, linker })
    }

    pub(crate) fn engine(&self) -> &Engine {
        &self.engine
    }

    pub(crate) fn linker(&self) -> &Linker<HostState> {
        &self.linker
    }
}

/// Builds store limits that cap every linear memory at `memory_limit_bytes`.
pub(crate) fn store_limits(memory_limit_bytes: usize) -> StoreLimits {
    StoreLimitsBuilder::new()
        .memory_size(memory_limit_bytes)
        .build()
}
